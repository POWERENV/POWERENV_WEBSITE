/**
 * This function retrieves the dashboard data for a specific PPool from the server and displays it in the PPool dashboard page, including setting up the event listeners for the interactive elements in that page.
 * @param {String} pgridID The ID of the PGrid to which the PPool belongs.
 * @param {String} ppoolID The ID of the PPool for which to retrieve and display the dashboard data.
 * @param {Object} e The event object generated by the user interaction that triggered the display of the PPool dashboard (e.g. clicking on the PPool name in the navigation tree), which can be used to position the dashboard page accordingly in relation to the clicked element.
 */
//=========================================================================================
export async function displayPPoolDashboardData(pgridID : Number, ppoolID : Number, e : Event | null)
{
    let dashboardData : typeDefinitions.PPoolDashboardData = await dataRetrievalScript.getPPoolDashboardData(pgridID, ppoolID) as typeDefinitions.PPoolDashboardData;
    await genericScript.switchCustomSection('ppool_mgmt.html', 'content', 'content');
    document.getElementById('content')!.scrollTop = 0;

    const centeredSettingsModalBoxContent = `<div>
        <h2>General</h2>
        <div class="centeredSettingsModalBoxSectionContent">
            <div class="centeredSettingsModalBoxSectionItem">
                <h3>PPool Name:</h3>
                <input type="text" value="${dashboardData.ppoolFullInfo.ppool_name}" spellcheck="false" />
            </div>
            <div class="centeredSettingsModalBoxSectionItem">
                <h3 style="height: 100px;">PPool Readme Text:</h3>
                <textarea spellcheck="false">${dashboardData.ppoolFullInfo.ppool_readme_text}</textarea>
            </div>
        </div>
    </div>
    
    <div style="margin-top: 300px;">
        <h2 style="color: var(--accent);">Danger Zone</h2>
        <div class="centeredSettingsModalBoxSectionContent">
            <div class="centeredSettingsModalBoxSectionItem" style="width: 20%;">
                <button id="ppoolDeleteBTN">DELETE PPOOL</button>
            </div>
        </div>
    </div>`;

    document.getElementById("editPPoolSettingsBTN")!.addEventListener("click", () => {
        const PPoolSettingsModalBox = new editorComponents.centeredSettingsModalBox("Edit PPool Settings", centeredSettingsModalBoxContent, () => {});

        document.getElementById("ppoolDeleteBTN")!.addEventListener("click", async (event : Event) => {
            console.log(dashboardData.ppoolFullInfo.ppool_id);
            await ppoolDataEditScript.DeletePPool(dashboardData.ppoolFullInfo.ppool_id);
            PPoolSettingsModalBox.hideSettingsBox();
            await pgridDataDisplayScript.displayPGridDashboardData(pgridID, event, true);
        });
    });

    displayPPoolMainInfo(dashboardData, pgridID, e);
    genericScript.resetElementEventListeners('_singleOperationBTN');

    //Assign Event Listeners to single/batch Operations View Switch Buttons
    document.getElementById('_singleOperationBTN')!.addEventListener('click', () => {
        toggleSingleNBatchOperationsTableView('_singleOperationBTN')
    });
    document.getElementById('_batchOperationBTN')!.addEventListener('click', () => {
        toggleSingleNBatchOperationsTableView('_batchOperationBTN')
    });

    //Make the current PNode the active node in the navigation tree
    mainScript.updateActiveTreeNode(dashboardData.ppoolFullInfo.ppool_name);

    document.getElementById("_hardware_link")!.classList.add('active');
    document.getElementById("_backToGridBTN")!.addEventListener("click", async () => {
        await pgridDataDisplayScript.displayPGridDashboardData(pgridID, e, false);
    });

    document.getElementById("changePPoolReadmeBTN")!.addEventListener("click", () => {
        const changesSaveOperation = (e : Event, selfInstance : editorComponents.sideConfigurationEditWizzard) => {
            const newReadmeTXT = (document.getElementById('readmeTextTextArea') as HTMLTextAreaElement)!.value;
            ppoolDataEditScript.PPoolUpdateReadmeText(ppoolID, pgridID, newReadmeTXT);
        };

        const readmeTextEditorBox = new editorComponents.sideConfigurationEditWizzard('Edit Readme Text', changesSaveOperation);
        readmeTextEditorBox.insertTextArea('readmeTextTextArea', 'Readme Text', 'Write Readme Text', dashboardData.ppoolFullInfo.ppool_readme_text, null);
    });

    displayPPoolsPnodesListInfo(dashboardData);
    displayPPoolPNodesLoginAudits(dashboardData);
    displayPPoolAttentionLEDMarkedPNodes(dashboardData);
    displayPPoolErrorLogsInfo(dashboardData);
    displayPPoolOperationHistory(dashboardData);
}

