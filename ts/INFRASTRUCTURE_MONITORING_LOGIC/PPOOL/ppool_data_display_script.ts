/**
 * Displays the main information for a PPool in the dashboard.
 * @param {Object} dashboardData The data containing the PPool information to display.
 * @param {String} _pgridID The ID of the PGrid to which the PPool belongs.
 * @param {Object} e The event object generated by the user interaction.
 */
//=========================================================================================
function displayPPoolMainInfo(dashboardData : typeDefinitions.PPoolDashboardData, _pgridID : Number, e : Event | null)
{
    document.getElementById("_ppoolName")!.innerText = dashboardData.ppoolFullInfo.ppool_name;
    document.getElementById("_propsPPoolName")!.innerText = dashboardData.ppoolFullInfo.ppool_name;
    document.getElementById("_propsPPoolID")!.innerText = dashboardData.ppoolFullInfo.ppool_id.toString();
    document.getElementById("_propsPPoolParentPGridName")!.innerText = dashboardData.ppoolFullInfo.ppool_parent_pgrid_name;
    document.getElementById("_propsPPoolCreationDatetime")!.innerText = dashboardData.ppoolFullInfo.ppool_creation_datetime;
    document.getElementById("_propsPPoolLastUpdateDatetime")!.innerText = dashboardData.ppoolFullInfo.ppool_last_update_datetime;
    document.getElementById("_propsPPoolTag")!.innerText = dashboardData.ppoolFullInfo.ppool_tag;
    document.getElementById("_propsPPoolPNodesCount")!.innerText = dashboardData.ppoolFullInfo.ppool_pnodes_count.toString();
    document.getElementById("_propsPPoolActivePNodesCount")!.innerText = dashboardData.ppoolFullInfo.ppool_active_pnodes_count.toString();
    document.getElementById("_ppoolReadmeTextParagraph")!.innerText = dashboardData.ppoolFullInfo.ppool_readme_text;
    document.getElementById("reloadSettingsBTN")!.addEventListener("click", async () => {
        await displayPPoolDashboardData(_pgridID, dashboardData.ppoolFullInfo.ppool_id, e);
    });
}

